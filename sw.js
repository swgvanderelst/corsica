const SDK = 'https://www.gstatic.com/firebasejs/12.0.0/';
const LEAFLET = 'https://cdnjs.cloudflare.com/ajax/libs/leaflet/1.9.4/';
const PRECACHE_EXTERNAL = [SDK + 'firebase-app.js', SDK + 'firebase-auth.js', SDK + 'firebase-database.js', LEAFLET + 'leaflet.min.css', LEAFLET + 'leaflet.min.js'];
const CACHED_HOSTS = ['fonts.googleapis.com', 'fonts.gstatic.com'];

self.addEventListener('install', e => {
  e.waitUntil((async () => {
    const c = await caches.open(VERSION);
    await c.addAll(SHELL.map(u => new Request(u, { cache: 'reload' }))); // bypass the HTTP cache; fail install on a missing shell file
    await c.addAll(DATA.filter(u => u.endsWith('.json')).map(u => new Request(u, { cache: 'reload' }))); // the data files must be there
    const images = DATA.filter(u => !u.endsWith('.json'));
    for (let i = 0; i < images.length; i += 12) await Promise.all(images.slice(i, i + 12).map(u => c.add(new Request(u, { cache: 'reload' })).catch(() => {}))); // images: in small batches, a miss is fetched later
    await Promise.all(PRECACHE_EXTERNAL.map(u => c.add(new Request(u, { mode: 'cors' })).catch(() => {})));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', e => {
  e.waitUntil((async () => {
    for (const k of await caches.keys()) if (k !== VERSION && k.startsWith('corsica-')) await caches.delete(k); // only our own caches: the origin is shared with other apps
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  const same = url.origin === self.location.origin;
  const external = CACHED_HOSTS.includes(url.hostname) || req.url.startsWith(SDK) || req.url.startsWith(LEAFLET);
  if (!same && !external) return; // Firebase data/auth traffic and map tiles are never intercepted
  if (same && url.pathname.includes('/api/')) return;
  e.respondWith((async () => {
    const c = await caches.open(VERSION);
    const hit = await c.match(req, { ignoreSearch: same }); // ?g=TOKEN must still hit the cached shell
    if (hit) return hit;
    try {
      const r = await fetch(req);
      if (r.ok || r.type === 'opaque') c.put(req, r.clone());
      return r;
    } catch (err) {
      if (req.mode === 'navigate') { const shell = await c.match('index.html'); if (shell) return shell; }
      throw err;
    }
  })());
});
